function guideById(id) { for (var i = 0; i < GUIDES.length; i++) if (GUIDES[i].id === id) return GUIDES[i]; return null; }
function guideText(g) {
  var t = [g.title, g.lead, g.cat].concat(g.summary || []);
  (g.sections || []).forEach(function (s) { t.push(s.h); t = t.concat(s.p || [], s.list || []); });
  return t.join(" ").replace(/<[^>]+>/g, "");
}
function guideCardHtml(g, feature) {
  var e = function (s) { var d = document.createElement("div"); d.textContent = s || ""; return d.innerHTML; };
  return '<a class="g-card' + (feature ? " feature" : "") + '" href="guide/' + g.id + '.html">' +
    '<div class="g-top"><span class="g-ico">' + g.ico + '</span><span class="chip region">' + e(g.cat) + '</span>' +
    (g.stage || []).slice(0, 2).map(function (s) { return '<span class="chip stage">' + e(stageLabel(s)) + '</span>'; }).join("") + '</div>' +
    '<h3>' + e(g.title) + '</h3><p>' + e(g.lead) + '</p>' +
    '<div class="g-foot"><span class="upd">✓ ' + g.updated.replace(/-/g, ".") + ' 확인</span><span>' + g.min + '분 읽기</span></div></a>';
}
function stageLabel(id) {
  for (var i = 0; i < GUIDE_STAGES.length; i++) if (GUIDE_STAGES[i].id === id) return GUIDE_STAGES[i].label;
  return id;
}
