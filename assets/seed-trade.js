var TRADE_BOARDS = ["구인구직","부동산","중고사고팔기","제주상점","동호회","특가공구","축제정보"];

/* ── 축제 상태 계산 ──
   예정 / 진행중 / 마감(종료 후 7일까지) / 만료(목록에서 제외) */
var FEST_KEEP_DAYS = 7;

function festStatus(p, today) {
  var now = today || new Date().toISOString().slice(0, 10);
  if (!p.start || !p.end) return p.head || "진행중";
  if (now < p.start) return "예정";
  if (now <= p.end) return "진행중";
  var end = new Date(p.end + "T00:00:00");
  var diff = Math.floor((new Date(now + "T00:00:00") - end) / 86400000);
  return diff <= FEST_KEEP_DAYS ? "마감" : "만료";
}

/* 종료 후 7일이 지난 축제는 제외한 목록 */
function activeFestivals() {
  var list = userPostsOf("축제정보").concat(TRADE_SEEDS.filter(function (p) { return p.board === "축제정보"; }));
  return list.filter(function (p) {
    if (p.kind === undefined) p.kind = /^(진행중|예정|마감|만료)$/.test(p.head || "") ? "" : (p.head || "");   // 글쓴이가 고른 축제 말머리는 kind 에 보관 (head 는 진행 상태로 바뀜)
    p.head = (p.start && p.end) || !p.kind ? festStatus(p) : "제보";   // 날짜 없는 회원 제보는 '제보'로 표시
    if (p.start && p.end) p.period = fmtPeriod(p.start, p.end);
    return p.head !== "만료";
  });
}

function fmtPeriod(s, e) {
  var a = s.split("-"), b = e.split("-");
  return (+a[1]) + "." + (+a[2]) + " ~ " + (a[0] === b[0] ? "" : (+b[0]) + ".") + (+b[1]) + "." + (+b[2]);
}

/* 회원이 쓴 글을 각 거래 페이지에 끼워넣기 */
function userPostsOf(board) {
  return localPosts().filter(function (p) { return p.board === board; });
}
