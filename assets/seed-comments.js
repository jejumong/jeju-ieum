  /* ── 고정 난수 ── */
  function seedOf(s) { var h = 2166136261; for (var i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
  function rng(seed) { return function () { seed |= 0; seed = seed + 0x6D2B79F5 | 0; var t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
  function weighted(r, w) { var x = r(), acc = 0; for (var i = 0; i < w.length; i++) { acc += w[i]; if (x < acc) return i; } return w.length - 1; }
  function addDays(d, n) { var a = d.split("-"); var s = new Date(Date.UTC(+a[0], +a[1] - 1, +a[2] + n)).toISOString().slice(0, 10); return s > TODAY ? TODAY : s; }

  /* 사이트 전체에서 이미 쓴 문구 */
  var USED = {};
  function take(r, arr) {
    var free = arr.filter(function (t) { return !USED[t]; });
    if (!free.length) return null;
    var t = free[Math.floor(r() * free.length)];
    USED[t] = 1;
    return t;
  }

  var COMMUNITY_W = [0.15, 0.22, 0.24, 0.2, 0.12, 0.07]; /* 0~5개 */
  var MARKET_W = [0.72, 0.2, 0.08];
  var ALL = null;

  function nickFor(r, usedNick) {
    var free = NICKS.filter(function (n) { return !usedNick[n]; });
    var n = free[Math.floor(r() * free.length)];
    usedNick[n] = 1;
    return n;
  }

  function topicPool(p) {
    function topicsIn(str) {
      var acc = [];
      TOPIC.forEach(function (t) {
        if (t.news && p.board !== "최신뉴스") return;
        if (t.k.test(str)) acc = acc.concat(t.c);
      });
      return acc;
    }
    var pool = topicsIn(p.title || "");
    if (!pool.length) pool = topicsIn(p.content || "");
    if (BOARD[p.board]) pool = pool.concat(BOARD[p.board]);
    return pool.concat(HEAD[p.head] || HEAD["기본"]);
  }

  function buildMarket(p, r) {
    var n = weighted(r, MARKET_W), out = [], d = p.date || TODAY;
    if (!n) return out;
    var q = take(r, MARKET);
    if (!q) return out;
    d = addDays(d, Math.floor(r() * 3));
    out.push({ author: nickFor(r, (function () { var u = {}; u[p.author] = 1; return u; })()), text: q, date: d });
    if (n === 2) {
      var a = take(r, MARKET_REPLY);
      if (a) out.push({ author: p.author, text: a, date: addDays(d, 1), reply: 0 });
    }
    return out;
  }

  function buildCommunity(p, r) {
    var count = weighted(r, COMMUNITY_W);
    if (!count) return [];
    var pool = topicPool(p), list = [], d = p.date || TODAY, usedNick = {};
    usedNick[p.author] = 1;

    /* 대댓글 자리를 하나 남겨둘지 정합니다 */
    var wantAuthor = count >= 2 && r() < 0.55;
    var wantPeer = !wantAuthor && count >= 3 && r() < 0.35;
    var topLevel = count - (wantAuthor || wantPeer ? 1 : 0);

    for (var j = 0; j < topLevel; j++) {
      var t = take(r, pool);
      if (!t) break;
      d = addDays(d, Math.floor(r() * 2));
      list.push({ author: nickFor(r, usedNick), text: t, date: d });
    }
    if (!list.length) return list;

    var parent = Math.floor(r() * list.length);
    var at = parent + 1;
    var pd = addDays(list[parent].date, Math.floor(r() * 2));
    if (wantAuthor) {
      var src = p.head === "질문" ? AUTHOR_Q : (p.head === "고민" || p.board === "질문하기") ? AUTHOR_W : AUTHOR_ETC;
      var a = take(r, src);
      if (a) list.splice(at, 0, { author: p.author, text: a, date: pd, reply: parent });
    } else if (wantPeer) {
      var pr = take(r, PEER);
      if (pr) list.splice(at, 0, { author: nickFor(r, usedNick), text: pr, date: pd, reply: parent });
    }
    /* 대댓글이 끼어들면서 뒤 번호가 밀린 만큼 날짜만 맞춥니다 */
    for (var k = at + 1; k < list.length; k++) if (list[k].date < list[k - 1].date && list[k].reply === undefined) list[k].date = list[k - 1].date;
    return list;
  }

  /* 글에 맞춰 직접 써 둔 댓글(p.cm) — t: 댓글, a: 작성자 답글, p: 다른 회원 답글 */
  function buildCustom(p, r) {
    var list = [], d = p.date || TODAY, usedNick = {}, lastTop = -1;
    usedNick[p.author] = 1;
    p.cm.forEach(function (c) {
      d = addDays(d, Math.floor(r() * 2));
      if (c[1] === "t") {
        list.push({ author: nickFor(r, usedNick), text: c[0], date: d });
        lastTop = list.length - 1;
      } else {
        list.push({ author: c[1] === "a" ? p.author : nickFor(r, usedNick), text: c[0], date: d, reply: lastTop });
      }
    });
    return list;
  }

  function buildAll() {
    ALL = {};
    var posts = (typeof allPosts === "function" ? allPosts() : []).slice()
      .sort(function (a, b) { return a.id < b.id ? -1 : a.id > b.id ? 1 : 0; });
    /* 직접 써 둔 댓글 문구는 다른 글에서 다시 쓰이지 않게 먼저 표시 */
    posts.forEach(function (p) { if (p.cm) p.cm.forEach(function (c) { USED[c[0]] = 1; }); });
    posts.forEach(function (p) {
      if (!p.id || isUserPost(p)) return;          /* 회원이 쓴 글은 제외 */
      var r = rng(seedOf(p.id));
      if (p.cm) { ALL[p.id] = buildCustom(p, r); return; }
      if (/^z\d\dn/.test(p.id)) { ALL[p.id] = []; return; } /* 새 글 중 댓글 없는 글 */
      if (p.board === "중고사고팔기") { ALL[p.id] = buildMarket(p, r); return; }
      if (typeof TRADE_BOARDS !== "undefined" && TRADE_BOARDS.indexOf(p.board) > -1) return;
      if (p.board === "공지") return;
      ALL[p.id] = buildCommunity(p, r);
    });
  }

